/*=============================================================================
  语音指令映射表
  必须与 SU03T 固件里每条命令词的"串口输出"数值完全一致
  （平台配置：A1~A7 命令词分别发送 1~7，A8 吼叫发 8，A9 滚发 9）
=============================================================================*/
#define CMD_NONE       0    /* 无指令（唤醒词不产生指令） */
#define CMD_STAND_UP   1    /* 起立 */
#define CMD_LIE_DOWN   2    /* 趴下 */
#define CMD_SIT        3    /* 坐下 */
#define CMD_FORWARD    4    /* 前进 */
#define CMD_BACK       5    /* 后退 */
#define CMD_LED_ON     6    /* 开灯，同时启动吼叫动态表情 */
#define CMD_LED_OFF    7    /* 关灯，同时停止动态表情并恢复平静 */
#define CMD_ROAR       8    /* 吼叫（播放 6 帧动图） */
#define CMD_ROLL       9    /* 滚（悲伤表情） */

/* 吼叫动图每帧停留时间：约 65ms -> 15 帧/秒 */
#define ROAR_FRAME_DELAY_MS  65

/*=============================================================================
  调试模式开关（第一次上电务必先用 1）
    0 = 正式模式：完整机器狗功能（舵机 + 语音 + 表情 + 灯）
    1 = 分模块自检：不初始化舵机、不做任何动作。上电跑一次跑马灯，
        然后 OLED 显示自检图案，串口回显收到的字节。
        —— 这一步先验证「板子 + 屏幕 + 串口」三件事，不用装舵机
    2 = 单舵机测试：只初始化舵机，四腿轮流慢慢扫 0 -> 90 -> 180 -> 0，
        用来确认每条腿的方向和行程（务必先只接一个舵机试！）
        ⚠ 实物舵机是 SG90（塑料齿，堵转易扫齿）：进这一步之前先把
          USER/SERVO/servo.h 里的 SERVO_CCR_MIN/MAX 改成 60/240（0.6~2.4ms），
          确认不顶死、没有"嗡嗡"堵转声，再放开到 50/250 取完整 180°
    3 = 姿态锁定：四腿停在复位姿态（水平朝前），屏幕显示 0，
        用来装舵盘/腿——装好后不要动，直接切到 0
=============================================================================*/
#define DEBUG_MODE           0   /* 0=正式模式（语音控制） */

void ShowFace(const u8 *pic);
void Roar_Play(void);
void Debug_SelfTest(void);

#endif
